function topic(section, title, what, how, extra, extra2, extra3, extra4) {
    var parts = ["<b>What it is</b><br>" + what, "<b>How to use it</b><br>" + how]
    if (extra)
        parts.push(extra)
    if (extra2)
        parts.push(extra2)
    if (extra3)
        parts.push(extra3)
    if (extra4)
        parts.push(extra4)
    return { "section": section, "title": title, "body": parts.join("<br><br>") }
}
